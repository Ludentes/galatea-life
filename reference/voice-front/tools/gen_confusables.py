"""Write voice_front/confusables.py from Unicode's confusables table.

    uv run python tools/gen_confusables.py

The standard folds "every character with a Cyrillic letter as its look-alike
in the Unicode confusables table (UTS #39)" to that letter. The table maps
each character to a prototype (its skeleton); a character is a Cyrillic
letter's look-alike when both have the same skeleton. The table is fetched,
checked against its pinned sha256, and never committed; the generated module
is, so the front needs no network and no table at run time.
"""
from __future__ import annotations

import hashlib
import sys
import urllib.request
from pathlib import Path

VERSION = "16.0.0"
URL = f"https://www.unicode.org/Public/security/{VERSION}/confusables.txt"
SHA256 = "95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611"
OUT = Path(__file__).resolve().parents[1] / "voice_front" / "confusables.py"

# The Russian alphabet, both cases. ё/Ё are outside U+0410..U+044F.
CYRILLIC = [chr(c) for c in range(0x0410, 0x0450)] + ["ё", "Ё"]


def fetch() -> str:
    with urllib.request.urlopen(URL, timeout=30) as r:
        data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != SHA256:
        sys.exit(f"{URL}: sha256 {got}, expected {SHA256}")
    return data.decode("utf-8-sig")


def skeletons(table: str) -> dict[str, str]:
    """Character -> prototype, for the single-character sources."""
    out: dict[str, str] = {}
    for line in table.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        source, target, _kind = (p.strip() for p in line.split(";"))
        if " " in source:
            continue
        out[chr(int(source, 16))] = "".join(chr(int(h, 16)) for h in target.split())
    return out


def fold_table(skel: dict[str, str]) -> dict[int, int]:
    def of(c: str) -> str:
        return skel.get(c, c)

    letter_of: dict[str, str] = {}
    for letter in CYRILLIC:
        # Two Russian letters never share a skeleton in 16.0.0; refuse a table
        # where they do rather than pick one silently.
        if of(letter) in letter_of:
            sys.exit(f"{letter!r} and {letter_of[of(letter)]!r} share a skeleton")
        letter_of[of(letter)] = letter
    candidates = set(skel) | {p for p in skel.values() if len(p) == 1}
    return {ord(c): ord(letter_of[of(c)]) for c in sorted(candidates)
            if c not in CYRILLIC and of(c) in letter_of}


def render(fold: dict[int, int]) -> str:
    rows = "\n".join(f"    0x{k:04X}: 0x{v:04X}," for k, v in sorted(fold.items()))
    return (
        '"""Generated by tools/gen_confusables.py from Unicode confusables '
        f'{VERSION}. Do not edit.\n\n'
        "Every character that has a Russian letter as its look-alike, mapped to that\n"
        'letter; for `str.translate`.\n"""\n\n'
        f'UNICODE_VERSION = "{VERSION}"\n\n'
        "FOLD: dict[int, int] = {\n" + rows + "\n}\n"
    )


def main() -> None:
    OUT.write_text(render(fold_table(skeletons(fetch()))), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
